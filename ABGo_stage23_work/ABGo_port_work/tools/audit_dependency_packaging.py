#!/usr/bin/env python3
"""Cross-check DT_NEEDED closure against bridge.cpp's host/guest library policy.

This is a packaging audit, not an ELF loader or runtime test. It uses readelf output
and verifies that every non-host dependency reachable from libABK.so has a bundled
ARM32 source library and a filename mapping in bridge.cpp.
"""
from pathlib import Path
import re, subprocess, sys

ROOT = Path(__file__).resolve().parents[1]
LIBDIR = ROOT / 'target_libs'
BRIDGE = (ROOT / 'bridge_src' / 'bridge.cpp').read_text(errors='replace')
HOST = {
    'libandroid.so', 'libEGL.so', 'libGLESv2.so', 'libjnigraphics.so',
    'liblog.so', 'libOpenSLES.so', 'libstdc++.so', 'libm.so', 'libc.so', 'libdl.so'
}

def needed(path):
    out = subprocess.check_output(['readelf', '-d', str(path)], text=True, errors='replace')
    return re.findall(r'Shared library: \[(.*?)\]', out)

def arm32(path):
    out = subprocess.check_output(['readelf', '-h', str(path)], text=True, errors='replace')
    return 'ELF32' in out and 'ARM' in out and 'little endian' in out.lower()

files = {p.name: p for p in LIBDIR.glob('*.so')}
soname_to_source = {p.name: p for p in files.values()}
# Validate that every guest SONAME maps to the exact suffix rule used by bridge.cpp.
map_match = re.search(r'if \(soname == "libgnustl_shared\.so".*?\) \{(.*?)\n    \}', BRIDGE, re.S)
issues = []
visited = set()
ordered = []

def walk(soname):
    if soname in HOST or soname in visited:
        return
    visited.add(soname)
    src = soname_to_source.get(soname)
    if src is None:
        issues.append(f'Missing guest source for DT_NEEDED {soname}')
        return
    if not arm32(src):
        issues.append(f'{src.name} is not identified by readelf as little-endian ARM ELF32')
    for dep in needed(src):
        walk(dep)
    ordered.append((soname, src.name))

walk('libABK.so')
# The bridge's mapping currently has explicit special cases for all guest dependency names.
for soname, _ in ordered:
    if soname != 'libABK.so' and soname not in HOST:
        if f'"{soname}"' not in BRIDGE:
            issues.append(f'No explicit guest_filename mapping visible for {soname}')

report = [
    '# Stage 13 — recursive dependency packaging audit', '',
    'Generated by `tools/audit_dependency_packaging.py` using `readelf` and the bridge source.', '',
    '**Scope:** validates the statically reachable DT_NEEDED closure from `libABK.so` against the current host-library allowlist and bundled ARM32 payload. It does not validate relocations, HLE ABI correctness, Android packaging, or runtime loading.', '',
    '## Dependency-first guest payload', '',
    '| SONAME | Source file |', '|---|---|'
]
for soname, src in ordered:
    report.append(f'| `{soname}` | `{src}` |')
report += ['', '## Host libraries skipped by guest loader', '']
for name in sorted(HOST): report.append(f'- `{name}`')
report += ['', '## Audit result', '']
if issues:
    report += ['**Issues found:**'] + [f'- {x}' for x in issues]
else:
    report += [f'No missing guest payloads detected in the reachable closure (**{len(ordered)} guest libraries**).', '', 'This is a packaging-closure result only; it does not mean the loader can resolve every imported symbol.']
report += ['', '## Re-run', '', '`python3 tools/audit_dependency_packaging.py`', '']
(ROOT / 'reports' / 'stage13_dependency_packaging.md').write_text('\n'.join(report))
print(f'Guest libraries in closure: {len(ordered)}')
print(f'Issues: {len(issues)}')
for issue in issues: print('ERROR:', issue)
sys.exit(1 if issues else 0)
