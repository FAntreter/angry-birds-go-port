#!/usr/bin/env python3
"""Inventory graphics/audio/native-window imports that need ABI-safe bridging.

This is static triage only. It deliberately does not claim that a symbol is
implemented merely because its name appears somewhere in the source.
"""
from pathlib import Path
import re, subprocess, sys

root = Path(__file__).resolve().parents[1]
libs = sorted((root / 'target_libs').glob('*.so'))
if not libs:
    raise SystemExit('No target ELF files found in target_libs')
source = '\n'.join(p.read_text(errors='ignore') for p in (root / 'bridge_src').glob('*') if p.is_file())
# Only HLE registration strings are treated as registered, not arbitrary mentions.
registered = set(re.findall(r'H\("([^"\n]+)"\s*,', source))

def undefined(path):
    out = subprocess.check_output(['readelf', '--dyn-syms', '--wide', str(path)], text=True, errors='replace')
    result = set()
    for line in out.splitlines():
        m = re.match(r'\s*\d+:\s+\S+\s+\S+\s+\S+\s+\S+\s+\S+\s+UND\s+(\S+)', line)
        if m:
            name = m.group(1).split('@', 1)[0]
            if name:
                result.add(name)
    return result

def bucket(name):
    if name.startswith('egl') or name.startswith('EGL_'): return 'EGL'
    if name.startswith('ANativeWindow') or name.startswith('AConfiguration'): return 'Native window/config'
    if name.startswith('sl') or name.startswith('SL_'): return 'OpenSL ES audio'
    if name.startswith('AAsset'): return 'Android assets'
    return None

rows=[]
for lib in libs:
    for sym in sorted(undefined(lib)):
        group=bucket(sym)
        if group:
            rows.append((lib.name, group, sym, 'registered HLE name' if sym in registered else 'no direct HLE registration found'))

out = ['# Stage 8 — graphics/audio/native-window boundary audit', '',
       'Generated by `tools/audit_graphics_audio_boundary.py` from the bundled ARM32 ELF dynamic symbol tables and HLE registration macros.', '',
       '**Scope:** static import inventory only. “No direct HLE registration found” is not a complete runtime failure diagnosis: a symbol may be resolved by a guest dependency, dynamic lookup, or host bridge path not recognized by this simple scan. Conversely, a name registration alone does not prove ABI correctness.', '',
       '## Findings', '']
for group in ['EGL', 'Native window/config', 'OpenSL ES audio', 'Android assets']:
    subset=[r for r in rows if r[1]==group]
    names=sorted({r[2] for r in subset})
    missing=sorted({r[2] for r in subset if r[3]!='registered HLE name'})
    out.append(f'### {group}')
    out.append(f'- Unique imported names: **{len(names)}**')
    out.append(f'- Names without direct HLE registration: **{len(missing)}**')
    if names:
        out.append('- Imported names: ' + ', '.join(f'`{x}`' for x in names))
    if missing:
        out.append('- No direct HLE registration: ' + ', '.join(f'`{x}`' for x in missing))
    out.append('')
out += ['## Engineering constraints',
        '1. EGL handles and native pointers cannot be passed through as 32-bit integers on a 64-bit host; use guest-visible tokens/handle tables and validate lifetimes.',
        '2. `eglCreateWindowSurface` needs a valid host `ANativeWindow*`, including lifecycle and ownership semantics; simply forwarding a guest integer is unsafe.',
        '3. `eglGetProcAddress` needs a controlled mapping from returned host function pointers to guest-callable thunks; returning raw 64-bit host addresses to ARM32 code is invalid.',
        '4. OpenSL ES exposes interface IDs and vtable-style interfaces. A symbol-only stub is insufficient; interface objects and callbacks need ABI translation.',
        '5. `AAsset_openFileDescriptor` uses native `off_t` output pointers. Confirm the guest ABI layout and 32-bit `off_t` contract before writing results into guest memory.',
        '', '## Validation command', '`python3 tools/audit_graphics_audio_boundary.py`', '']
report = root / 'reports' / 'stage8_graphics_audio_boundary.md'
report.write_text('\n'.join(out))
print(f'Wrote {report.relative_to(root)} ({len(rows)} categorized symbol/library rows)')
for group in ['EGL', 'Native window/config', 'OpenSL ES audio', 'Android assets']:
    subset=[r for r in rows if r[1]==group]
    print(f'{group}: {len({r[2] for r in subset})} unique imports, {len({r[2] for r in subset if r[3] != "registered HLE name"})} without direct HLE registration')
